#!/usr/bin/env python3
# Regenerates src/testdata.h.
#
# The compression oracles used here are NOT part of the shipped tool, they only
# produce the reference streams the C++ decoder is checked against:
#   * LZO    : minilzo (lzo1x_1_compress) from https://github.com/nemequ/lzo
#   * Snappy : cramjam  (pip install cramjam)
#
#   ./lzo_oracle c plain.bin stream.lzo          # see tests/README.md
#   python3 tests/gen_testdata.py > src/testdata.h
import random, sys

def emit_array(name, data):
    print("static const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 16):
        print("    " + ",".join("0x%02x" % b for b in data[i:i+16]) + ",")
    print("};")
    print("static const size_t %s_len = %d;" % (name, len(data)))
    print()

def lzo_compress(data, oracle):
    import subprocess, tempfile, os
    with tempfile.NamedTemporaryFile(delete=False) as f:
        f.write(data); src = f.name
    dst = src + ".lzo"
    subprocess.run([oracle, "c", src, dst], check=True, capture_output=True)
    with open(dst, "rb") as f: out = f.read()
    os.unlink(src); os.unlink(dst)
    return out

def main():
    oracle = sys.argv[1] if len(sys.argv) > 1 else "/tmp/oracle/lzo_oracle"
    try:
        import cramjam
        have_snappy = True
    except Exception:
        have_snappy = False

    random.seed(20240910)
    samples = {}

    text = (b"Metin2 unpack client - EterPack test vector.\n" * 12
            + bytes(random.randrange(256) for _ in range(120))
            + b"d:/ymir art/effect/etc/game/2013_back02.dds\n" * 8)
    samples["text"] = text

    noise = bytes(random.randrange(256) for _ in range(600))
    samples["noise"] = noise

    runs = b"\xAA" * 900 + b"abcdefgh" * 3 + b"\x00" * 400 + b"tail data " * 60
    samples["runs"] = runs

    binary = bytes(range(256)) * 3 + b"\x00\x01\x02\x03" * 40
    samples["binary"] = binary

    print("// SPDX-License-Identifier: MIT")
    print("// Generated by tests/gen_testdata.py - reference streams produced with")
    print("// minilzo (LZO1X) and cramjam (Snappy). Do not edit by hand.")
    print("#pragma once")
    print("#include <cstddef>")
    print()

    for name, data in samples.items():
        emit_array("kPlain_" + name, data)
        emit_array("kLzo_" + name, lzo_compress(data, oracle))
        if have_snappy:
            emit_array("kSnappy_" + name, bytes(cramjam.snappy.compress_raw(data)))
        print()

if __name__ == "__main__":
    main()
