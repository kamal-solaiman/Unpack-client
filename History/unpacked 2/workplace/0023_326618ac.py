#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Mission Config Generator

This script converts the server's mission_quest.txt to the client's missionpoolconfig.py

Usage:
    python generate_mission_config.py [path_to_mission_quest.txt]

If no path is provided, it will look for the file in common server locations.

Example:
    python generate_mission_config.py "../../../servers/srv2_test/srv2_test/share/systems/config_systems/mission_quest.txt"
"""

import os
import sys
import re
from datetime import datetime

# Default paths to search for mission_quest.txt
DEFAULT_PATHS = [
    "../../../../servers/srv2_live/srv2_live/share/systems/config_systems/mission_quest.txt",
]

OUTPUT_FILE = "missionpoolconfig.py"

def parse_mission_quest_file(filepath):
    """Parse the server's mission_quest.txt file and extract mission data"""

    if not os.path.exists(filepath):
        print("Error: File not found: %s" % filepath)
        return None

    with open(filepath, 'r') as f:
        content = f.read()

    # Structure to hold parsed data
    missions = {
        0: {0: [], 1: [], 2: []},  # Daily slots 0, 1, 2
        1: {0: [], 1: [], 2: []},  # Weekly slots 0, 1, 2
    }

    # Find all Group blocks for missions (MissionCat0_num0, MissionCat1_num2, etc.)
    group_pattern = r'Group\s+MissionCat(\d+)_num(\d+)\s*\{([^}]+)\}'

    for match in re.finditer(group_pattern, content, re.DOTALL):
        category = int(match.group(1))  # 0 = Daily, 1 = Weekly
        slot = int(match.group(2))      # 0, 1, or 2
        block_content = match.group(3)

        if category not in missions:
            missions[category] = {}
        if slot not in missions[category]:
            missions[category][slot] = []

        # Parse mission lines: mission_N	type	target	count	minLevel	maxLevel
        mission_pattern = r'mission_\d+\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)'

        for mission_match in re.finditer(mission_pattern, block_content):
            mission_type = int(mission_match.group(1))
            target = int(mission_match.group(2))
            count = int(mission_match.group(3))
            min_level = int(mission_match.group(4))
            max_level = int(mission_match.group(5))

            mission_tuple = (mission_type, target, count, min_level, max_level)

            # Avoid duplicates
            if mission_tuple not in missions[category][slot]:
                missions[category][slot].append(mission_tuple)

    return missions

def generate_python_config(missions, output_path):
    """Generate the missionpoolconfig.py file from parsed mission data"""

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = []
    lines.append("# Mission Pool Configuration")
    lines.append("# Auto-generated by generate_mission_config.py on %s" % timestamp)
    lines.append("# This file mirrors the server's mission_quest.txt for client-side mission preview")
    lines.append("#")
    lines.append("# To regenerate this file, run:")
    lines.append("#   python generate_mission_config.py [path_to_mission_quest.txt]")
    lines.append("#")
    lines.append("# Format: (missionType, targetVnum, count, minLevel, maxLevel)")
    lines.append("#")
    lines.append("# Mission Types:")
    lines.append("# 1 = TYPE_MONSTERS (Kill monsters)")
    lines.append("# 2 = TYPE_STONES (Destroy metin stones)")
    lines.append("# 3 = TYPE_BOSSES (Kill bosses)")
    lines.append("# 4 = TYPE_MINING (Mining)")
    lines.append("# 5 = TYPE_FISHING (Fishing)")
    lines.append("# 6 = TYPE_DUNGEON (Complete dungeon)")
    lines.append("# 7 = TYPE_USE_ITEM (Submit/use items)")
    lines.append("# 8 = TYPE_WRITE_SHOUT (Write shout messages)")
    lines.append("# 9 = TYPE_USE_ITEM_SWITCH (Attribute switching)")
    lines.append("")

    # Generate Daily missions
    for slot in range(3):
        if slot in missions.get(0, {}):
            lines.append("# Daily Missions - Slot %d" % slot)
            lines.append("DAILY_SLOT_%d = [" % slot)
            lines.append("\t# (type, target, count, minLevel, maxLevel)")
            for mission in missions[0][slot]:
                lines.append("\t%s," % str(mission))
            lines.append("]")
            lines.append("")

    # Generate Weekly missions
    for slot in range(3):
        if slot in missions.get(1, {}):
            lines.append("# Weekly Missions - Slot %d" % slot)
            lines.append("WEEKLY_SLOT_%d = [" % slot)
            lines.append("\t# (type, target, count, minLevel, maxLevel)")
            for mission in missions[1][slot]:
                lines.append("\t%s," % str(mission))
            lines.append("]")
            lines.append("")

    # Generate combined structure
    lines.append("# Combined structure for easy access")
    lines.append("# MISSION_POOL[category][slot] = list of missions")
    lines.append("MISSION_POOL = {")
    lines.append("\t0: {  # Daily")
    for slot in range(3):
        lines.append("\t\t%d: DAILY_SLOT_%d," % (slot, slot))
    lines.append("\t},")
    lines.append("\t1: {  # Weekly")
    for slot in range(3):
        lines.append("\t\t%d: WEEKLY_SLOT_%d," % (slot, slot))
    lines.append("\t},")
    lines.append("}")
    lines.append("")

    # Add helper functions
    lines.append("def GetMissionPoolByCategory(category):")
    lines.append("\t\"\"\"Get all missions for a category (0=Daily, 1=Weekly)\"\"\"")
    lines.append("\tif category not in MISSION_POOL:")
    lines.append("\t\treturn {}")
    lines.append("\treturn MISSION_POOL[category]")
    lines.append("")
    lines.append("def GetMissionPoolBySlot(category, slot):")
    lines.append("\t\"\"\"Get missions for a specific slot\"\"\"")
    lines.append("\tif category not in MISSION_POOL:")
    lines.append("\t\treturn []")
    lines.append("\tif slot not in MISSION_POOL[category]:")
    lines.append("\t\treturn []")
    lines.append("\treturn MISSION_POOL[category][slot]")
    lines.append("")
    lines.append("def GetFilteredMissions(category, playerLevel):")
    lines.append("\t\"\"\"Get all missions for a category filtered by player level\"\"\"")
    lines.append("\tresult = []")
    lines.append("\tif category not in MISSION_POOL:")
    lines.append("\t\treturn result")
    lines.append("")
    lines.append("\tfor slot, missions in MISSION_POOL[category].items():")
    lines.append("\t\tfor mission in missions:")
    lines.append("\t\t\tmissionType, target, count, minLevel, maxLevel = mission")
    lines.append("\t\t\tif minLevel <= playerLevel <= maxLevel:")
    lines.append("\t\t\t\tresult.append((slot, missionType, target, count, minLevel, maxLevel))")
    lines.append("")
    lines.append("\treturn result")
    lines.append("")
    lines.append("def GetAllFilteredMissions(playerLevel):")
    lines.append("\t\"\"\"Get all missions (daily + weekly) filtered by player level\"\"\"")
    lines.append("\treturn {")
    lines.append("\t\t0: GetFilteredMissions(0, playerLevel),")
    lines.append("\t\t1: GetFilteredMissions(1, playerLevel),")
    lines.append("\t}")
    lines.append("")

    # Write to file
    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))

    return True

def main():
    print("=" * 60)
    print("Mission Config Generator")
    print("=" * 60)
    print("")

    # Determine input file path
    input_path = None

    if len(sys.argv) > 1:
        input_path = sys.argv[1]
        print("Using provided path: %s" % input_path)
    else:
        print("No path provided, searching default locations...")
        for path in DEFAULT_PATHS:
            full_path = os.path.join(os.path.dirname(__file__), path)
            if os.path.exists(full_path):
                input_path = full_path
                print("Found: %s" % path)
                break

    if not input_path:
        print("")
        print("Error: Could not find mission_quest.txt")
        print("")
        print("Please provide the path as an argument:")
        print("  python generate_mission_config.py <path_to_mission_quest.txt>")
        print("")
        print("Or place the file in one of these locations:")
        for path in DEFAULT_PATHS:
            print("  - %s" % path)
        return 1

    # Parse the server config
    print("")
    print("Parsing: %s" % input_path)
    missions = parse_mission_quest_file(input_path)

    if not missions:
        print("Error: Failed to parse mission config")
        return 1

    # Count missions
    total_missions = 0
    print("")
    print("Parsed missions:")
    for category in [0, 1]:
        cat_name = "Daily" if category == 0 else "Weekly"
        for slot in range(3):
            count = len(missions.get(category, {}).get(slot, []))
            total_missions += count
            print("  %s Slot %d: %d missions" % (cat_name, slot, count))

    print("")
    print("Total: %d missions" % total_missions)

    # Generate output file
    output_path = os.path.join(os.path.dirname(__file__), OUTPUT_FILE)
    print("")
    print("Generating: %s" % output_path)

    if generate_python_config(missions, output_path):
        print("")
        print("=" * 60)
        print("SUCCESS! Generated %s" % OUTPUT_FILE)
        print("=" * 60)
        print("")
        print("The client-side mission config has been updated.")
        print("Make sure to pack this file into your client distribution.")
        return 0
    else:
        print("Error: Failed to generate config")
        return 1

if __name__ == "__main__":
    sys.exit(main())
