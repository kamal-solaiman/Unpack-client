# The client's stripped Python 2.7 ships no json module (game_data.py parses the
# baked cl_*.json with eval() for the same reason). Parse via a sandboxed eval
# with the JSON literals bound -- importing json here would abort the whole wiki
# import chain at boot (the __hybrid_import partial-module / "no attribute
# 'ToolTip'" trap).
_JSON_GLOBALS = {"__builtins__": {}, "true": True, "false": False, "null": None}

# ---------------------------------------------------------------------------
# Data source: a loose UserData/wiki/dungeons_wiki.json overrides the packed
# copy on the test server (same dev-override convention as loose wiki pages),
# so authors iterate without repacking. Production reads the packed file only.
# ---------------------------------------------------------------------------

_JSON_NAME = "dungeons_wiki.json"
_cache = None
_bonusLabels = None


def _DevMode():
	# Author/dev gate: server test-server flag OR a local wiki_dev.key file
	# (server-independent escape hatch), matching SimpleTextLoader._WikiDevMode.
	if app.IsEnableTestServerFlag():
		return True
	try:
		kf = open("UserData/wiki/" + "wiki_dev.key", "r")
		kf.close()
		return True
	except:
		return False


def _ReadJsonText(name=None):
	# Loose UserData first in dev, else the packed wiki/ copy. Returns the raw
	# text, or None if neither is readable.
	name = name or _JSON_NAME
	paths = []
	if _DevMode():
		paths.append("UserData/wiki/" + name)
	paths.append("wiki/" + name)
	for p in paths:
		try:
			f = open(p, "r")
			try:
				return f.read()
			finally:
				try:
					f.close()
				except:
					pass
		except:
			continue
	return None


def LoadDungeons(force=False):
	# Parse (and cache) the dungeon table. Returns {} on any failure so callers
	# never crash the wiki over a bad/missing file.
	global _cache
	if _cache is not None and not force:
		return _cache
	_cache = {}
	txt = _ReadJsonText()
	if not txt:
		return _cache
	try:
		data = eval(txt, dict(_JSON_GLOBALS))
		_cache = data.get("dungeons", {}) or {}
	except Exception:
		try:
			dbg.TraceError("[wikidungeon] failed to parse %s" % _JSON_NAME)
		except:
			pass
		_cache = {}
	return _cache


def Reload():
	# Drop the cache so the next Get re-reads from disk (dev live-reload).
	global _cache, _skillPower
	_cache = None
	_skillPower = None
	return LoadDungeons(force=True)


_skillPower = None


def _LoadSkillPower():
	# skill_power.json is generated by tools/"wiki server to client"/
	# gen_skill_power.py from the common-DB SKILL_POWER_BY_LEVEL rows. Returns
	# {} when absent -- the skill table then hides its computed-value column.
	global _skillPower
	if _skillPower is not None:
		return _skillPower
	_skillPower = {}
	txt = _ReadJsonText("skill_power.json")
	if not txt:
		return _skillPower
	try:
		_skillPower = eval(txt, dict(_JSON_GLOBALS)) or {}
	except Exception:
		try:
			dbg.TraceError("[wikidungeon] failed to parse skill_power.json")
		except:
			pass
		_skillPower = {}
	return _skillPower


def GetDungeon(dungeonId):
	# Return one dungeon dict by id (string or int), or None. Skips entries
	# flagged "hidden".
	dungeons = LoadDungeons()
	d = dungeons.get(str(dungeonId))
	if d is None:
		return None
	if d.get("hidden"):
		return None
	return d


def ListDungeonIds():
	# Ids of all non-hidden dungeons, numeric order.
	dungeons = LoadDungeons()
	ids = []
	for k, v in dungeons.items():
		if v and not v.get("hidden"):
			try:
				ids.append(int(k))
			except:
				pass
	ids.sort()
	return ids


# ---------------------------------------------------------------------------
# Localisation: getattr(localeinfo, key, default) does NOT fall back in this
# client -- the wrapper returns "Locale not found: KEY". LocaleText checks for
# that sentinel so a key missing before the locale .epk repack still renders
# the English default. New keys must be added to BOTH en and ae
# new_locale_game.txt in the same change.
# ---------------------------------------------------------------------------

def LocaleText(key, default):
	value = getattr(localeinfo, key, default)
	try:
		if not value or value.startswith("Locale not found"):
			return default
	except AttributeError:
		return default
	return value


def _TokenText(token):
	# Race / element tokens (ANIMAL, WIND, ...) -> localised label, English
	# token as the pre-repack fallback.
	if not token:
		return ""
	return LocaleText("WIKI_DUNGEON_TOKEN_" + str(token).upper(), str(token))


