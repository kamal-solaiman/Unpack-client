class WikiDungeonWindow(ui.Window):
	# JSON-driven dungeon guide page. One instance is reused for every dungeon;
	# OpenDungeon(id) rebuilds the section widgets from the cached JSON. Modelled
	# on SimpleTextLoader's scroll container (peekWindow clip mask + scrollBoard
	# that slides in Y). Phase 1 renders the Dungeon Information section only.
	SCROLL_SPEED = 50

	def __init__(self):
		ui.Window.__init__(self)
		self.SetSize(_BOARD_W, _BOARD_H)

		self.dungeonId = None
		# Widgets are dropped and rebuilt per dungeon. Hold every code-created
		# child on one of these lists -- SetParent does NOT keep a Python object
		# alive, so a local would be GC'd and render nothing.
		self.elements = []
		self.renderTargets = []

		# Async drop-grid state. Drops load through the engine
		# (wiki.LoadInfo -> InGameWiki.BINARY_LoadInfo -> NoticeMe), so the
		# grid may fill a frame or two after the page opens.
		self.toolTip = uitooltip.ItemToolTip()
		self.skillToolTip = uitooltip.SkillToolTip()
		self._bossVnum = 0
		self._panelY = 0
		self._dropsDone = False
		self._equipAttrs = {}

		self.scrollBar = None

		self.peekWindow = ui.Window()
		self.peekWindow.SetParent(self)
		self.peekWindow.AddFlag("attach")
		self.peekWindow.AddFlag("not_pick")
		self.peekWindow.SetSize(self.GetWidth() - 8 - 5, self.GetHeight() - 5)
		self.peekWindow.SetPosition(5, 5)
		if not app.USE_CLIP_MASK:
			self.peekWindow.SetInsideRender(True)
		self.peekWindow.Show()

		self.scrollBoard = ui.Window()
		self.scrollBoard.SetParent(self.peekWindow)
		self.scrollBoard.AddFlag("attach")
		self.scrollBoard.AddFlag("not_pick")
		if app.USE_CLIP_MASK:
			self.scrollBoard.SetClippingMaskWindow(self.peekWindow)
		self.scrollBoard.Show()

		self._RegisterScrollBar()
		self.Hide()

	# -- scroll plumbing (mirrors SimpleTextLoader) -------------------------

	def _RegisterScrollBar(self):
		import ingamewikiui
		self.scrollBar = ingamewikiui.WikiScrollBar()
		self.scrollBar.SetParent(self)
		self.scrollBar.SetPosition(self.peekWindow.GetLocalPosition()[0] + self.peekWindow.GetWidth() + 1, self.peekWindow.GetLocalPosition()[1])
		self.scrollBar.SetSize(7, self.peekWindow.GetHeight())
		self.scrollBar.SetScrollEvent(self.OnScrollBar)
		self.scrollBar.SetScrollSpeed(self.SCROLL_SPEED)
		self.scrollBar.Show()

	def OnRunMouseWheel(self, length):
		if self.peekWindow.IsInPosition():
			self.UpdateScrollbar(int((length * 0.01) * self.SCROLL_SPEED))
			return True
		return False

	def OnScrollBar(self, fScale):
		span = self.scrollBoard.GetHeight() - self.peekWindow.GetHeight()
		curr = min(0, max(math.ceil(span * fScale * -1.0), -span))
		self.scrollBoard.SetPosition(0, curr)

	def ChangeScrollbar(self):
		if not self.scrollBar:
			return
		if self.scrollBoard.GetHeight() <= self.peekWindow.GetHeight():
			self.scrollBar.Hide()
		else:
			self.scrollBar.SetScale(self.peekWindow.GetHeight(), self.scrollBoard.GetHeight())
			self.scrollBar.SetPosScale(truediv(abs(self.scrollBoard.GetLocalPosition()[1]), (self.scrollBoard.GetHeight() - self.peekWindow.GetHeight())))
			self.scrollBar.Show()

	def UpdateScrollbar(self, val=0):
		curr = min(0, max(self.scrollBoard.GetLocalPosition()[1] + val, -self.scrollBoard.GetHeight() + self.peekWindow.GetHeight()))
		self.scrollBoard.SetPosition(0, curr)
		self.ChangeScrollbar()

	# -- widget factories ---------------------------------------------------

	def _Img(self, path, x, y, parent=None):
		img = ui.ExpandedImageBox()
		img.SetParent(parent or self.scrollBoard)
		img.AddFlag("attach")
		img.AddFlag("not_pick")
		img.LoadImage(path)
		img.SetPosition(int(x), int(y))
		img.Show()
		self.elements.append(img)
		return img

	def _Bar(self, x, y, w, h, color):
		bar = ui.Bar()
		bar.SetParent(self.scrollBoard)
		bar.AddFlag("attach")
		bar.AddFlag("not_pick")
		bar.SetPosition(int(x), int(y))
		bar.SetSize(int(w), int(h))
		bar.SetColor(color)
		bar.Show()
		self.elements.append(bar)
		return bar

	def _Text(self, s, x, y, color=_COL_VALUE, parent=None, align="left"):
		t = ui.TextLine()
		t.SetParent(parent or self.scrollBoard)
		t.AddFlag("attach")
		t.AddFlag("not_pick")
		if align == "center":
			t.SetHorizontalAlignCenter()
		elif align == "right":
			t.SetHorizontalAlignRight()
		else:
			t.SetHorizontalAlignLeft()
		t.SetPosition(int(x), int(y))
		t.SetText(s)
		t.SetPackedFontColor(color)
		t.Show()
		self.elements.append(t)
		return t

	# -- lifecycle ----------------------------------------------------------

	def _ClearContent(self):
		for w in self.elements:
			try:
				w.Hide()
			except:
				pass
		del self.elements[:]
		for rt in self.renderTargets:
			try:
				rt.Hide()
			except:
				pass
		# Dropping the ref triggers WikiRenderTarget.__del__ (unregisters the
		# engine model-view module) on the next GC pass.
		del self.renderTargets[:]
		self._equipAttrs = {}
		self.scrollBoard.SetPosition(0, 0)
		self.scrollBoard.SetSize(self.peekWindow.GetWidth(), self.peekWindow.GetHeight())

	def OpenDungeon(self, dungeonId, buildKey=None):
		self._ClearContent()
		self.dungeonId = dungeonId
		self._dropsDone = False

		data = GetDungeon(dungeonId)
		if not data:
			self._Text(LocaleText("WIKI_DUNGEON_NO_DATA", "No dungeon data."), 20, 20, _COL_LABEL)
			self.Show()
			return

		# Build variants ("builds": [{"key", "name_key", "data"}, ...]): the
		# base entry IS the first build; later builds overlay their "data"
		# keys wholesale. The tab strip only renders when the key is present.
		builds = data.get("builds") or []
		self._buildKey = None
		if builds:
			keys = [str(b.get("key", "")) for b in builds]
			if buildKey not in keys:
				buildKey = keys[0]
			self._buildKey = buildKey
			merged = dict(data)
			del merged["builds"]
			for b in builds:
				if str(b.get("key", "")) == buildKey:
					merged.update(b.get("data") or {})
					break
			data = merged

		y = 4
		if builds:
			y = self._RenderBuildTabs(builds, y)
		y = self._RenderInfoSection(data, y)
		y = self._RenderEquipSection(data, y)
		y = self._RenderBonusSection(data, y)
		y = self._RenderBiologSection(data, y)
		y = self._RenderSkillSection(data, y)
		y = self._RenderCompanionSection(data, y)
		y = self._RenderConsumableSection(data, y)

		self.scrollBoard.SetSize(self.peekWindow.GetWidth(), max(y, self.peekWindow.GetHeight()))
		self.scrollBoard.SetPosition(0, 0)
		self.ChangeScrollbar()
		self.Show()

		self._RequestDrops()

	def _OnBuildTab(self, buildKey):
		if buildKey == getattr(self, "_buildKey", None):
			return
		self.OpenDungeon(self.dungeonId, buildKey)

	# Brush-stroke tab art (170x26): normal / hover / selected states.
	_TAB_ART = "d:/ymir work/ui/wiki/new_wiki/wiki_tab_"
	_TAB_W, _TAB_H = 170, 26

	def _RenderBuildTabs(self, builds, y):
		# Centred strip of art buttons (Duo / Solo I / ...). The active tab is
		# held in its "selected" visual via Button.Down(); clicking another tab
		# rebuilds the page on that build (the proven DS-page rebuild idiom).
		# RTL reverses the tab ORDER only -- the strip stays centred.
		gap = 12
		total = len(builds) * self._TAB_W + (len(builds) - 1) * gap
		x = (556 - total) / 2
		try:
			ordered = builds[::-1] if localeinfo.IsARABIC() else builds
		except:
			ordered = builds
		for b in ordered:
			key = str(b.get("key", ""))
			label = LocaleText(str(b.get("name_key", "")), key.capitalize())
			active = (key == self._buildKey)
			btn = ui.Button()
			btn.SetParent(self.scrollBoard)
			btn.SetUpVisual(self._TAB_ART + "normal.png")
			btn.SetOverVisual(self._TAB_ART + "hover.png")
			btn.SetDownVisual(self._TAB_ART + "selected.png")
			btn.SetPosition(x, y)
			if app.USE_CLIP_MASK:
				try:
					btn.SetSubClippingMaskWindow(self.peekWindow)
				except:
					pass
			btn.SetText(label)
			btn.SetTextColor(_COL_TAN if active else self._COL_TABLE_VALUE)
			if active:
				btn.Down()
			else:
				btn.SAFE_SetEvent(self._OnBuildTab, key)
			btn.Show()
			self.elements.append(btn)
			x += self._TAB_W + gap
		return y + self._TAB_H + 8

	# -- sections -----------------------------------------------------------

	def _RenderInfoSection(self, data, y):
		# Layout is driven by dungeon_layout.png (556x233, RTL-mirrored): a baked
		# 3x4 drop-slot grid on the LEFT, a boss area in the middle gap, and 6
		# brush-stroke info bars (star bullet on the far RIGHT). A dark title
		# banner (dungeon_small_header.png, 289x40) sits above the panel.
		# Positions are a first pass -- fine-tune in-client with UI_DEBUGGER.

		try:
			self._bossVnum = int(data.get("boss_vnum", 0))
		except:
			self._bossVnum = 0

		# --- Title banner ---
		self._Img(_ART + "dungeon_small_header.png", (556 - 289) / 2, y)
		name = LocaleText(data.get("name_key", ""), "")
		if not name:
			try:
				name = nonplayer.GetMonsterName(self._bossVnum)
			except:
				name = ""
		self._Text(name, 264, y + 12, _COL_TITLE, align="center")

		# --- Panel background ---
		panelY = y + 48
		self._panelY = panelY
		self._Img(_ART + "dungeon_layout.png", 0, panelY)

		# --- Live 3D boss in the middle gap (between the drop grid and the
		# info bars), inside the 135x183 preview frame ---
		self._RenderBoss(data, 216, panelY + 24)

		# --- Info rows on the 6 RIGHT brush bars (RTL-mirrored art; star
		# bullets are baked on the far right). Kept left-aligned per request --
		# only the anchor X moves into the right-bar region. The dungeon name
		# leads (label=None -> bare text) so every bar carries a row. ---
		rows = [(None, name, _COL_TITLE)] + self._InfoRows(data)
		barY = [18, 52, 86, 120, 154, 188]
		for i in xrange(min(len(rows), len(barY))):
			label, value, color = rows[i]
			text = value if label is None else "%s : %s" % (label, value)
			self._Text(text, 510, panelY + barY[i], color, align="left")

		# --- View Drop button (bottom-left, under the mirrored drop grid;
		# position confirmed in-client with UI_DEBUGGER: local 57,223) ---
		self._RenderViewDrop(data, 57, panelY + 171)

		return panelY + 233 + 8

	def _InfoRows(self, data):
		# Each row: (label, value, color). Everything is _COL_TAN except the
		# min-DPS ("damage") row, which is _COL_DMG.
		rows = []
		lim = data.get("level_limit")
		if lim and len(lim) >= 2:
			rows.append((LocaleText("WIKI_DUNGEON_LEVEL_LIMIT", "Level Limit"), "%d - %d" % (lim[0], lim[1]), _COL_TAN))
		# Tokens resolve through the matching bonus's existing localized label
		# ("ORC" -> APPLY_ATTBONUS_ORC -> "Strong vs Orcs"), which is
		# self-descriptive -- so these rows carry no "label :" prefix.
		strong = data.get("strength_bonus") or []
		if strong:
			rows.append((None, ", ".join([self._BonusTokenText(t, "ATTBONUS_") for t in strong]), _COL_TAN))
		elem = data.get("resistance_bonus") or []
		if elem:
			rows.append((None, ", ".join([self._BonusTokenText(t, "RESIST_") for t in elem]), _COL_TAN))
		dps = data.get("min_dps")
		if isinstance(dps, dict):
			dps = dps.get(self._PlayerRaceKey())
		if dps:
			rows.append((LocaleText("WIKI_DUNGEON_MIN_DPS", "Min DPS"), str(dps), _COL_DMG))
		# pvm_skill_level is the recommended PvM skill level -- it belongs in the
		# Recommended Skills section (P4), not the dungeon-info stat rows.
		cd = data.get("cooldown")
		if cd:
			try:
				rows.append((LocaleText("WIKI_DUNGEON_COOLDOWN", "Cooldown"), "%d min" % (int(cd) / 60), _COL_TAN))
			except:
				pass
		return rows

	def _BonusTokenText(self, token, applyPrefix):
		# No per-token locale keys: "ORC"/"WIND" etc. reuse the bonus label
		# the character-details window already localizes. Unknown tokens fall
		# back to the legacy WIKI_DUNGEON_TOKEN_* key / raw token.
		name = applyPrefix + str(token).upper()
		applyType = getattr(item, "APPLY_" + name, 0)
		if applyType:
			label = self._BonusLabel(name, applyType)
			if label:
				return label
		return _TokenText(token)

