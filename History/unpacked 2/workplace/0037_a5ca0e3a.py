	def _OnViewDrop(self, bossVnum):
		if not bossVnum:
			return
		# Reuse the existing monster detail page -- it already renders the real
		# server drop table for the boss vnum.
		self._OpenPageWithHistory(bossVnum, True)

	# -- drop grid (baked 3x4 slots on the LEFT of dungeon_layout.png) -------
	# Anchor + pitch measured from the baked slot borders in dungeon_layout.png
	# (slot columns at art x 28/71/114/157, rows at y 31/74/117 -> pitch 43; a
	# 32px cell centred in the 26px-wide slot lands at x0=25) and confirmed
	# in-client with UI_DEBUGGER (first slot at local 25,86 -> y0=34).
	_DROP_X0 = 25
	_DROP_Y0 = 34
	_DROP_CX = 43
	_DROP_RY = 43
	_DROP_MAX = 12
	# Icons are scaled to fit this box. Item art is NOT uniformly 32x32 -- weapons
	# and armour ship 32x64 (and larger), which is what pushed icons out of the
	# baked slot grid and past the panel edge.
	_DROP_CELL = 32

	def _RequestDrops(self):
		# Same engine path the boss detail page uses: mob info is loaded async;
		# GetMobInfo is valid only once IsSet returns true. If it isn't ready,
		# register for the BINARY_LoadInfo -> NoticeMe callback and fill later.
		if not self._bossVnum:
			return
		if wiki.IsSet(self._bossVnum, True):
			self._FillDropGrid()
			return
		try:
			wikiBase = wiki.GetBaseClass()
			if wikiBase is not None and long(id(self)) not in wikiBase.objList:
				wikiBase.objList[long(id(self))] = proxy(self)
			wiki.LoadInfo(long(id(self)), self._bossVnum, True)
		except:
			pass

	def NoticeMe(self):
		# Engine callback: a mob-info load finished. Fill the grid if it's ours.
		if self._bossVnum and wiki.IsSet(self._bossVnum, True):
			self._FillDropGrid()

	def _FillDropGrid(self):
		if self._dropsDone:
			return
		try:
			lst = wiki.GetMobInfo(self._bossVnum)
		except:
			lst = None
		if not lst:
			return
		self._dropsDone = True

		# Real drop table, keyed for count lookup by the pinned rows below.
		counts = {}
		ordered = []
		for entry in lst:
			v = entry[0]
			if v < wiki.CONTROL_ITEM_VNUM:
				continue
			if v in counts:
				continue
			try:
				counts[v] = int(entry[1])
			except (IndexError, TypeError, ValueError):
				counts[v] = 0
			ordered.append(v)

		# Every boss leads with its own box and coin, in that order, whether or
		# not the drop table happens to list them first.
		rows = []
		seen = set()
		data = GetDungeon(self.dungeonId) or {}
		for key in ("box_vnum", "coin_vnum"):
			try:
				v = int(data.get(key, 0))
			except (TypeError, ValueError):
				v = 0
			if v and v not in seen:
				seen.add(v)
				rows.append((v, counts.get(v, 0)))

		for v in ordered:
			if v in seen:
				continue
			seen.add(v)
			rows.append((v, counts[v]))
			if len(rows) >= self._DROP_MAX:
				break

		for idx in xrange(len(rows)):
			col = idx % 4
			row = idx // 4
			x = self._DROP_X0 + col * self._DROP_CX
			y = self._panelY + self._DROP_Y0 + row * self._DROP_RY
			self._ItemIcon(rows[idx][0], x, y, rows[idx][1])

	def _ItemIcon(self, vnum, x, y, count=0, cellW=None, cellH=None, anchorTop=False):
		# Shared item icon: scaled into the slot, optional count, hover tooltip,
		# click-through to the item's wiki page. Default cell is the drop-grid
		# 32px box; equipment panels pass their own baked slot boxes (incl. the
		# tall weapon/armor cells, which a 32x64 icon fills unscaled). anchorTop
		# docks short art to the first frame of a multi-frame stack instead of
		# floating it in the middle (owner-tuned: dagger in the 3-frame weapon
		# column).
		cw = self._DROP_CELL if cellW is None else int(cellW)
		ch = self._DROP_CELL if cellH is None else int(cellH)
		item.SelectItem(vnum)

		# ExpandedImageBox, not ImageBox: only the Expanded variant can be scaled
		# AND is the only one that honours SetSubClippingMaskWindow, so a row
		# scrolled past the viewport doesn't bleed over the rest of the page.
		icon = ui.ExpandedImageBox()
		icon.SetParent(self.scrollBoard)
		icon.LoadImage(item.GetIconImageFileName())

		iw = icon.GetWidth() or cw
		ih = icon.GetHeight() or ch
		scale = min(float(cw) / iw, float(ch) / ih, 1.0)
		if scale < 1.0:
			icon.SetScale(scale, scale)
			iw = int(iw * scale)
			ih = int(ih * scale)

		# Centre whatever the scaled art measures inside the slot so mixed
		# 32x32 / 32x64 icons still line up on the baked grid.
		ix = int(x) + (cw - iw) / 2
		iy = int(y) if anchorTop else int(y) + (ch - ih) / 2
		icon.SetPosition(ix, iy)
		if app.USE_CLIP_MASK:
			try:
				icon.SetSubClippingMaskWindow(self.peekWindow)
			except:
				pass

		icon.SAFE_SetStringEvent("MOUSE_OVER_IN", self._OnDropOver, vnum)
		icon.SAFE_SetStringEvent("MOUSE_OVER_OUT", self._OnDropOut)
		# "mouse_click" (fired from OnMouseLeftButtonUp), NOT the MOUSE_LEFT_DOWN
		# string event: SAFE_SetStringEvent stores into eventArgs while
		# ImageBox.OnMouseLeftButtonDown reads argDict, so that path never fires.
		icon.SAFE_SetEvent(self._OnDropClick, "mouse_click", vnum)
		icon.Show()
		self.elements.append(icon)

		if count > 1:
			num = ui.NumberLine()
			num.SetParent(self.scrollBoard)
			num.AddFlag("not_pick")
			num.SetHorizontalAlignRight()
			num.SetPosition(int(x) + cw - 1, int(y) + ch - 13)
			num.SetNumber(str(count))
			if app.USE_CLIP_MASK:
				try:
					num.SetSubClippingMaskWindow(self.peekWindow)
				except:
					pass
			num.Show()
			self.elements.append(num)

		return icon

	def _OnDropOver(self, vnum):
		if not self.toolTip:
			return
		# Recommended bonuses ride in as the item's regular attribute slots, so
		# they render exactly like rolled bonuses (same block, same colors).
		attrSlot = 0
		attrs = self._equipAttrs.get(vnum)
		if attrs:
			attrSlot = attrs[:player.ATTRIBUTE_SLOT_MAX_NUM]
			attrSlot += [(0, 0)] * (player.ATTRIBUTE_SLOT_MAX_NUM - len(attrSlot))
		self.toolTip.ClearToolTip()
		self.toolTip.AddItemData(vnum, [0 for i in xrange(player.METIN_SOCKET_MAX_NUM)], attrSlot, noRender=True)
		self.toolTip.AppendWikiAccessoryMaterials(vnum)

	def _OnDropOut(self):
		if self.toolTip:
			self.toolTip.Hide()

	def _OnDropClick(self, eventType, vnum):
		# eventType is the "mouse_click" key ui.py passes back as args[0].
		self._OpenPageWithHistory(vnum, False)

	def _OpenPageWithHistory(self, vnum, isMonster):
		# Hand OpenSpecialPage this page as `oldWindow` so it becomes history[0]
		# and the Back button lights up. NOT CloseBaseWindows() first -- that
		# wipes windowHistory and disables both nav buttons, which is exactly why
		# there was no way back from a boss/item page opened here.
		wikiClass = wiki.GetBaseClass()
		if not wikiClass or not vnum:
			return
		wikiClass.OpenSpecialPage(self, int(vnum), bool(isMonster))

