	def _EquipEntry(self, race_eq, gen_eq, key):
		# Race-specific entry wins over the shared one, so the JSON author may
		# place any key in either table (weapon skins can be per-class).
		for src in (race_eq, gen_eq):
			entry = src.get(key)
			if entry and entry.get("vnum"):
				return entry
		# Pre-panel data used costume_mount for the mount-skin idea; keep it
		# feeding the MOUNT SKIN slot until the JSONs migrate to mount_skin.
		if key == "mount_skin":
			return self._EquipEntry(race_eq, gen_eq, "costume_mount")
		return None

	def _ResolveAttrs(self, attrs):
		# JSON attr names ("MAX_HP") -> (item.APPLY_MAX_HP, value) pairs the
		# tooltip can format through its AFFECT_DICT. Unknown names are skipped
		# so a typo in the data can't break the hover.
		if not attrs:
			return None
		resolved = []
		for name in sorted(attrs.keys()):
			applyType = getattr(item, "APPLY_" + str(name), 0)
			try:
				value = int(attrs[name])
			except (TypeError, ValueError):
				value = 0
			if applyType and value:
				resolved.append((applyType, value))
		return resolved or None

