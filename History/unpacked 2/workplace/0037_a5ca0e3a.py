	# -- Recommended Skills -------------------------------------------------
	# "recommended_skills": [{"skill_index": N, "skill_level": raw,
	# "races": [...]}, ...] -- rows filtered to the player's class (entries
	# without "races" are for everyone). The value column evaluates the
	# skill's REAL formula at the recommended level: percentage from the baked
	# skill_power.json (common-DB SKILL_POWER_BY_LEVEL rows), fed to
	# skill.GetNewAffectData -- the same path the skill tooltip uses. The old
	# hardcoded "apply_value" JSON field is ignored.

	_SKILL_JOBS = {"warrior": 0, "assassin": 1, "sura": 2, "shaman": 3, "wolfman": 4}
	_SKILL_COLS = (50, 105, 105)   # status / my level / recommended; skill icon gets the rest
	_SKILL_GRADE_BASE = {0: 0, 1: 19, 2: 29, 3: 39}
	# Buffi companion skills (Hosin/Gicheon/Kwaesok/Jeungryeok). Their level
	# lives in the *New skill APIs (registered slots 130+), not the player's
	# own slot table, and their power curve is not job-specific.
	_BUFFI_SKILL_FIRST = 163
	_BUFFI_SKILL_LAST = 166
	# PvM Class Balance passive: state is server-pushed into
	# constinfo.PVM_BALANCE (game.RecvPvmBalanceInfo), not the skill slots,
	# and it renders through its own dedicated tooltip.
	_PVM_BALANCE_SKILL = 216
	# USE_PASSIVE_ABILITY skills (crit 210 / monster 211 / hp 212 / masters
	# 213-215): learned into normal skill slots but rendered by the dedicated
	# passive tooltip; like 216 they ship no per-grade icon art, and neither
	# does Leadership (121).
	_PASSIVE_ABILITY_FIRST = 210
	_PASSIVE_ABILITY_LAST = 215
	_LEADERSHIP_SKILL = 121

	def _IsPassiveAbility(self, skillIndex):
		if skillIndex == self._PVM_BALANCE_SKILL:
			return True
		return self._PASSIVE_ABILITY_FIRST <= skillIndex <= self._PASSIVE_ABILITY_LAST

	def _IsBuffiSkill(self, skillIndex):
		return self._BUFFI_SKILL_FIRST <= skillIndex <= self._BUFFI_SKILL_LAST

	def _SkillPowerRow(self, forBuffi=False):
		power = _LoadSkillPower()
		if not power:
			return None
		if forBuffi:
			return power.get("generic")
		job = self._SKILL_JOBS.get(self._PlayerRaceKey(), 0)
		try:
			group = net.GetMainActorSkillGroup()
		except:
			group = 0
		row = None
		if group in (1, 2):
			row = (power.get("types") or {}).get(str(job * 2 + (group - 1)))
		return row or power.get("generic")

	# Conditional master passives: no learnable level -- "achieved" is computed
	# from their requirement sets, mirroring uitooltip's master checklists.
	_SKILL_MASTER = 213
	_PASSIVE_MASTER = 214
	_PASSIVE_MASTER_REQ = (210, 211, 212, 121)

	def _MySkillRawLevel(self, skillIndex):
		# player.GetSkillLevel returns the IN-GRADE level once mastered
		# (M1 = raw 20 -> 1); rebuild the raw 0-40 scale from the grade.
		if skillIndex == self._SKILL_MASTER:
			try:
				for s in xrange(1, 7):
					if not player.GetSkillIndex(s):
						return 0
					if player.GetSkillLevel(s) + self._SKILL_GRADE_BASE.get(player.GetSkillGrade(s), 0) < 40:
						return 0
			except:
				return 0
			return 40
		if skillIndex == self._PASSIVE_MASTER:
			for req in self._PASSIVE_MASTER_REQ:
				if self._MySkillRawLevel(req) < 40:
					return 0
			return 40
		if self._IsBuffiSkill(skillIndex):
			grade = player.GetSkillGradeNew(skillIndex)
			level = player.GetSkillLevelNew(skillIndex)
			return level + self._SKILL_GRADE_BASE.get(grade, 0)
		if skillIndex == self._PVM_BALANCE_SKILL:
			info = getattr(constinfo, "PVM_BALANCE", None) or {}
			if not info.get("bound"):
				return 0
			return int(info.get("level", 0)) + self._SKILL_GRADE_BASE.get(int(info.get("grade", 0)), 0)
		slot = player.GetSkillSlotIndex(skillIndex)
		if slot < 0:
			return 0
		grade = player.GetSkillGrade(slot)
		level = player.GetSkillLevel(slot)
		return level + self._SKILL_GRADE_BASE.get(grade, 0)

	def _SkillLevelText(self, raw):
		if raw <= 0:
			return "-"
		if raw < 20:
			return str(raw)
		if raw < 30:
			return "M%d" % (raw - 19)
		if raw < 40:
			return "G%d" % (raw - 29)
		return "P"

	def _OnSkillOver(self, idx, reco):
		# Skill values live on the icon's hover tooltip: the real formula
		# evaluated at the RECOMMENDED level. AppendSkillLevelDescriptionNew is
		# the tooltip's own renderer; its percentage argument is a 0-1
		# fraction (same as GetSkillCurrentEfficientPercentage), so the baked
		# power-table value divides by 100.
		tip = self.skillToolTip
		if self._IsPassiveAbility(idx):
			# Dedicated renderer: value table + state (balance/crit/monster/...).
			tip.SetPassiveAbilityToolTip(idx)
			return
		tip.ClearToolTip()
		try:
			tip.SetTitle(skill.GetSkillName(idx))
		except:
			tip.SetTitle(str(idx))
		tip.AppendSpace(5)
		tip.AppendTextLine("%s: %s" % (LocaleText("WIKI_DUNGEON_BONUS_RECO", "Recommended"), self._SkillLevelText(reco)), tip.NORMAL_COLOR)
		row = self._SkillPowerRow(forBuffi=self._IsBuffiSkill(idx))
		if row:
			pct = row[min(max(reco, 0), len(row) - 1)] / 100.0
			tip.AppendSkillLevelDescriptionNew(idx, pct, tip.ENABLE_COLOR)
		tip.AlignHorizonalCenter()
		tip.ShowToolTip()

	def _OnSkillOut(self):
		if self.skillToolTip:
			self.skillToolTip.HideToolTip()

